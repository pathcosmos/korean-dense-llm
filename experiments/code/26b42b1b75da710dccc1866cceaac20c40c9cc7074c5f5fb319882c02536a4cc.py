"""Code-only cleaner: preserve retained content exactly and keep provenance.
Usage: python data/clean_code.py SOURCE [WORKERS=2]
SOURCE must have its own pinned raw download_manifest.json. No web normalization.
"""
import collections
from concurrent.futures import ProcessPoolExecutor, as_completed
import hashlib
import json
import os
from pathlib import Path
import re
import sys
os.environ.setdefault('NUMEXPR_NUM_THREADS', '8')
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.paths import DATA
from data.dedup import atomic_json
import pyarrow as pa
import pyarrow.parquet as pq

LICENSES = {'mit', 'apache-2.0', 'bsd-2-clause', 'bsd-3-clause', 'isc', 'cc0-1.0', 'unlicense'}
LANGUAGES = {'.py': 'Python', '.pyw': 'Python', '.js': 'JavaScript', '.jsx': 'JavaScript',
             '.ts': 'TypeScript', '.tsx': 'TypeScript', '.c': 'C', '.h': 'C/C++ header',
             '.cpp': 'C++', '.cc': 'C++', '.cxx': 'C++', '.hpp': 'C++', '.hxx': 'C++',
             '.java': 'Java', '.go': 'Go', '.rs': 'Rust', '.sql': 'SQL', '.sh': 'Shell', '.bash': 'Shell'}
EXCLUDED_PARTS = {'vendor', 'node_modules', 'third_party', 'third-party', 'dist', 'build', '__pycache__'}
BENCH_REPOS = {'human-eval', 'human_eval', 'mbpp', 'bigcodebench', 'evalplus'}
GENERATED = re.compile(r'@generated|automatically generated|generated by|do not edit', re.I)
SECRET = re.compile(r'-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----|AKIA[0-9A-Z]{16}|ghp_[A-Za-z0-9]{36}')
POLICY = dict(version='code-v1', allowed_license_metadata=sorted(LICENSES), languages=LANGUAGES,
              excluded_parts=sorted(EXCLUDED_PARTS), benchmark_repo_names=sorted(BENCH_REPOS),
              min_chars=20, max_chars=200000, max_line=2000, max_mean_line=200,
              generated_regex=GENERATED.pattern, secret_regex=SECRET.pattern,
              content_policy='byte-preserving UTF8, no whitespace/case/PII rewriting',
              dedup_policy='exact UTF8 SHA256 within shard, no Unicode normalization; cross-shard/source separate')
POLICY_HASH = hashlib.sha256(json.dumps(POLICY, sort_keys=True).encode()).hexdigest()
SCHEMA = pa.schema([('text', pa.string()), ('h', pa.int64()), ('repo_name', pa.string()),
                    ('path', pa.string()), ('license', pa.string()), ('language', pa.string()),
                    ('source_row', pa.int64()), ('content_sha256', pa.string())])


def select_code(row):
    """Return (original content, language, rejection). Never rewrite retained content."""
    text = row.get('content')
    if not isinstance(text, str):
        return None, None, 'non_string'
    license_name = (row.get('license') or '').lower()
    path = (row.get('path') or '').replace('\\', '/')
    parts = path.lower().split('/')
    name = Path(path).suffix.lower()
    language = LANGUAGES.get(name)
    if name == '.c' and Path(path).suffix == '.C':
        language = 'C++'
    if license_name not in LICENSES:
        return None, language, 'license_not_selected'
    if language is None:
        return None, None, 'language_not_selected'
    if EXCLUDED_PARTS.intersection(parts):
        return None, language, 'vendor_or_build'
    repo = (row.get('repo_name') or '').split('/')[-1].lower()
    if repo in BENCH_REPOS or any(x in BENCH_REPOS for x in parts):
        return None, language, 'known_benchmark'
    if len(text) < POLICY['min_chars'] or not text.strip():
        return None, language, 'short'
    if len(text) > POLICY['max_chars']:
        return None, language, 'long'
    if '\x00' in text or text.count('\ufffd') / len(text) > .001:
        return None, language, 'encoding'
    if GENERATED.search(text[:3000]):
        return None, language, 'generated'
    lines = text.splitlines()
    if max(map(len, lines), default=0) > POLICY['max_line'] or len(text) / max(1, len(lines)) > POLICY['max_mean_line']:
        return None, language, 'minified_or_long_lines'
    if SECRET.search(text):
        return None, language, 'secret_pattern'
    return text, language, None


def work(args):
    source, path = args
    file = Path(path)
    out = Path(DATA) / 'clean' / source / file.name
    signature = dict(input_size=file.stat().st_size, input_mtime_ns=file.stat().st_mtime_ns, policy_hash=POLICY_HASH)
    marker = Path(str(out) + '.done')
    if marker.exists():
        old = json.loads(marker.read_text())
        if any(old.get(k) != v for k, v in signature.items()):
            raise RuntimeError('Code input/policy changed; use a new output source: ' + str(out))
        stats = json.loads(Path(str(out) + '.stats.json').read_text())
        if pq.ParquetFile(out).metadata.num_rows != stats['counts'].get('kept', 0):
            raise RuntimeError('Output row count mismatch')
        return file.name, stats
    if out.exists():
        raise RuntimeError('Unmarked code output exists; refusing overwrite: ' + str(out))
    out.parent.mkdir(parents=True, exist_ok=True)
    counts, languages = collections.Counter(), collections.Counter()
    seen = set(); chars = total_bytes = 0; row_index = 0
    with pq.ParquetWriter(str(out) + '.tmp', SCHEMA, compression='zstd') as writer:
        for batch in pq.ParquetFile(file).iter_batches(batch_size=1024, columns=['repo_name', 'path', 'license', 'content']):
            output = []
            for row in batch.to_pylist():
                text, language, reason = select_code(row)
                if reason is None:
                    digest = hashlib.sha256(text.encode()).digest()
                    if digest in seen:
                        reason = 'exact_duplicate'
                    else:
                        seen.add(digest)
                        output.append(dict(text=text, h=int.from_bytes(digest[:8], 'little', signed=True),
                                           repo_name=row['repo_name'], path=row['path'], license=row['license'],
                                           language=language, source_row=row_index,
                                           content_sha256=hashlib.sha256(text.encode()).hexdigest()))
                        chars += len(text); total_bytes += len(text.encode()); languages[language] += 1
                counts[reason or 'kept'] += 1
                row_index += 1
            if output:
                writer.write_table(pa.Table.from_pylist(output, schema=SCHEMA))
    Path(str(out) + '.tmp').replace(out)
    stats = dict(counts=dict(counts), chars_kept=chars, utf8_bytes_kept=total_bytes, languages=dict(languages))
    atomic_json(Path(str(out) + '.stats.json'), stats)
    atomic_json(marker, signature)
    return file.name, stats


def main():
    import argparse
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('source', choices=['github_code_pilot', 'github_code_v1'])
    ap.add_argument('workers', nargs='?', type=int, default=2)
    a = ap.parse_args()
    if a.workers < 1:
        ap.error('workers must be positive')
    raw = Path(DATA) / 'raw' / a.source
    manifest = json.loads((raw / 'download_manifest.json').read_text())
    files = [raw / name for name in manifest['files']]
    if not all(f.exists() for f in files):
        raise RuntimeError('Download is not complete')
    output = Path(DATA) / 'clean' / a.source
    output.mkdir(parents=True, exist_ok=True)
    policy = dict(policy=POLICY, policy_hash=POLICY_HASH, source_manifest=manifest)
    policyfile = output / 'policy.json'
    if policyfile.exists() and json.loads(policyfile.read_text()) != policy:
        raise RuntimeError('Code policy changed; choose a new output source')
    if not policyfile.exists():
        atomic_json(policyfile, policy)
    totals = collections.Counter(); languages = collections.Counter(); chars = size = 0
    with ProcessPoolExecutor(a.workers) as pool:
        jobs = [pool.submit(work, (a.source, str(f))) for f in files]
        for i, job in enumerate(as_completed(jobs), 1):
            name, st = job.result();totals.update(st['counts']);languages.update(st['languages'])
            chars += st['chars_kept'];size += st['utf8_bytes_kept']
            print(f'[{i}/{len(files)}]', name, json.dumps(st['counts']), flush=True)
    report = dict(counts=dict(totals), languages=dict(languages), chars_kept=chars,
                  utf8_bytes_kept=size, policy_hash=POLICY_HASH)
    atomic_json(output / 'summary.json', report)
    atomic_json(output / '.done', dict(shards=len(files), policy_hash=POLICY_HASH))
    print('DONE CODE', json.dumps(report), flush=True)


if __name__ == '__main__':
    main()
