import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import pyarrow as pa
import pyarrow.parquet as pq
from data import clean_code
from data.dedup import fingerprint


class CodeCleanerTest(unittest.TestCase):
    def row(self, text, **kwargs):
        return dict(content=text, path='src/main.py', repo_name='org/project', license='mit', **kwargs)

    def test_reference_D03_preserves_semantic_differences(self):
        cases = json.loads((Path(__file__).resolve().parents[1] / 'docs/reviews/frankenstallm/acceptance_cases.json').read_text())['cases']
        case = next(c for c in cases if c['id'] == 'D03')
        actual = []
        for left, right in case['inputs']['pairs']:
            # Supply context to satisfy the declared minimum-length quality policy.
            prefix = '# Reference regression sample\r\n'
            a, _, ar = clean_code.select_code(self.row(prefix + left))
            b, _, br = clean_code.select_code(self.row(prefix + right))
            self.assertIsNone(ar); self.assertIsNone(br)
            self.assertEqual(a, prefix + left); self.assertEqual(b, prefix + right)
            actual.append(fingerprint(a) == fingerprint(b))
        self.assertEqual(actual, case['expected']['treat_as_exact_duplicates'])

    def test_filter_without_rewriting(self):
        text = '# A valid short source file\nX = 1\n'
        for field, value, reason in [('license', 'gpl-3.0', 'license_not_selected'),
                                     ('path', 'vendor/main.py', 'vendor_or_build'),
                                     ('repo_name', 'org/human-eval', 'known_benchmark')]:
            row = self.row(text);row[field] = value
            self.assertEqual(clean_code.select_code(row)[2], reason)
        self.assertEqual(clean_code.select_code(self.row('# generated by a tool\nx = 1\n'))[2], 'generated')
        self.assertEqual(clean_code.select_code(self.row('# credential fixture\nkey = "' + 'AKIA' + 'A' * 16 + '"'))[2], 'secret_pattern')
        self.assertEqual(clean_code.select_code(self.row(text))[0], text)

    def test_provenance_resume_and_policy_validation(self):
        with tempfile.TemporaryDirectory() as tmp, patch.object(clean_code, 'DATA', tmp):
            f = Path(tmp) / 'input.parquet'
            text = '# keep original content\nif ready:\n    run()\n'
            pq.write_table(pa.Table.from_pylist([self.row(text), self.row(text), self.row('# unicode string literal\nmessage = "é"\n'), self.row('# unicode string literal\nmessage = "e\u0301"\n')]), f)
            _, stats = clean_code.work(('github_code_pilot', str(f)))
            self.assertEqual(stats['counts'], dict(kept=3, exact_duplicate=1))
            out = Path(tmp) / 'clean/github_code_pilot/input.parquet'
            row = pq.read_table(out).to_pylist()[0]
            self.assertEqual(row['text'], text)
            self.assertEqual((row['repo_name'], row['source_row']), ('org/project', 0))
            before = out.stat().st_mtime_ns
            clean_code.work(('github_code_pilot', str(f)))
            self.assertEqual(out.stat().st_mtime_ns, before)
            with patch.object(clean_code, 'POLICY_HASH', 'changed'):
                with self.assertRaisesRegex(RuntimeError, 'policy changed'):
                    clean_code.work(('github_code_pilot', str(f)))
